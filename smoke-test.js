// Smoke test: node smoke-test.js   (needs: npm i playwright && npx playwright install chromium)
const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const b = await chromium.launch(), p = await b.newPage({ viewport: { width: 390, height: 844 } }), errs = [];
  p.on('pageerror', e => errs.push(String(e))); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  await p.goto('file://' + path.resolve(__dirname, 'index.html'));
  const check = (name, ok) => { console.log((ok ? 'PASS ' : 'FAIL ') + name); if (!ok) process.exitCode = 1; };
  await p.click('.row[data-i="0"]'); await p.click('#tog'); await p.click('#g'); await p.click('[data-k="chess"]');
  await p.waitForSelector('#bd .sq', { timeout: 9000 });
  const sizes = await p.$$eval('#bd .sq', els => els.map(e => e.offsetHeight));
  check('chess squares are all equal height', new Set(sizes).size === 1);
  await p.click('[data-q="e2"]'); await p.click('[data-q="e4"]'); await p.waitForTimeout(2500);
  check('opponent replied (it is white to move again)', await p.evaluate(() => __t.g.t === 'w'));
  await p.click('#x'); await p.click('#tog'); await p.click('#g'); await p.click('[data-k="bg"]'); await p.waitForSelector('.pt');
  await p.click('#rl'); await p.waitForTimeout(300);
  check('backgammon dice are shown after rolling', await p.$$eval('.dice img.dc', els => els.length >= 2 && els.every(e => e.complete && e.naturalWidth > 0)));
  await p.click('#x'); await p.click('#tog'); await p.click('#c'); await p.waitForSelector('.mc');
  const titles = await p.$$eval('.mc', els => els.map(e => e.getAttribute('aria-label')));
  check('cinema lists exactly the two films (' + titles.join(' | ') + ')', titles.length === 2 && titles[0] === 'Ashes of Honor' && titles[1] === 'The Lost Canyon');
  await p.click('.mc[data-i="0"]'); await p.waitForSelector('.scr2.hasv video', { timeout: 12000 }); await p.waitForTimeout(2500);
  const v1 = await p.evaluate(() => { const v = document.querySelector('.scr2 video'); return { t: v.currentTime, paused: v.paused, ready: v.readyState, muted: v.muted, w: v.videoWidth } });
  check('film clip is really playing (t=' + v1.t.toFixed(2) + 's, ' + v1.w + 'px wide)', !v1.paused && v1.t > 0.5 && v1.ready >= 2 && v1.muted);
  await p.waitForTimeout(3000); await p.click('#pp'); await p.waitForTimeout(400);
  check('pause button pauses the clip', await p.evaluate(() => document.querySelector('.scr2 video').paused));
  await p.click('#pp'); await p.waitForTimeout(600);
  check('resume plays it again', await p.evaluate(() => !document.querySelector('.scr2 video').paused));
  await p.click('#x'); await p.waitForTimeout(300);
  check('video element is gone after ending the session', await p.evaluate(() => document.querySelectorAll('video').length === 0));
  check('no console or page errors', errs.length === 0);
  // fallback: block the clips, the poster experience must still work
  const p2 = await b.newPage({ viewport: { width: 390, height: 844 } }), errs2 = [];
  p2.on('pageerror', e => errs2.push(String(e)));
  await p2.route('**/assets/video/**', r => r.abort());
  await p2.goto('file://' + path.resolve(__dirname, 'index.html')); await p2.waitForSelector('#list .row'); await p2.click('.row[data-i="0"]');
  await p2.click('#tog'); await p2.click('#c'); await p2.click('.mc[data-i="0"]'); await p2.waitForSelector('.scr2.run', { timeout: 12000 }); await p2.waitForTimeout(1500);
  check('fallback: poster is shown when the clip cannot load', await p2.evaluate(() => !document.querySelector('.scr2').classList.contains('hasv') && !document.querySelector('.scr2 video')) && errs2.length === 0);
 if (errs.length) console.log(errs);
  await b.close();
})();
